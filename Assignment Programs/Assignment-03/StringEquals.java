class EqualsExample {
    public static void main(String[] args) {
        String str1 = "Java";
        String str2 = "Java";

        boolean result = str1.equals(str2);

        System.out.println("First String: " + str1);
        System.out.println("Second String: " + str2);
        System.out.println("Are they equal? " + result);
    }
}
